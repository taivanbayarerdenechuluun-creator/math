// Derives the PostgreSQL schema and its migrations from prisma/schema.prisma (single source of truth).
// Usage: npm run db:gen-postgres
//  - first run: writes prisma/postgres/migrations/0001_init for the whole schema
//  - later runs: keep every existing migration untouched (an applied migration must never change) and add ONE new
//    migration containing only the difference between the previous PostgreSQL schema and the new one
const fs = require("fs");
const os = require("os");
const path = require("path");
const { execFileSync } = require("child_process");

const root = path.join(__dirname, "..");
const out = path.join(root, "prisma", "postgres");
const migrations = path.join(out, "migrations");
const schemaFile = path.join(out, "schema.prisma");
const src = fs.readFileSync(path.join(root, "prisma", "schema.prisma"), "utf8");
if (!/provider\s*=\s*"sqlite"/.test(src)) throw new Error("prisma/schema.prisma must use the sqlite provider as its source");

const pg = src.replace(/provider\s*=\s*"sqlite"/, 'provider = "postgresql"');
const previous = fs.existsSync(schemaFile) ? fs.readFileSync(schemaFile, "utf8") : null;
fs.mkdirSync(migrations, { recursive: true });
fs.writeFileSync(schemaFile, pg);

const env = { ...process.env, DATABASE_URL: "postgresql://user:pass@localhost:5432/intelliq" };
const prisma = path.join(root, "node_modules", ".bin", process.platform === "win32" ? "prisma.cmd" : "prisma");
const run = (args, opts = {}) => execFileSync(prisma, args, { env, shell: process.platform === "win32", ...opts });
run(["validate", "--schema", schemaFile], { stdio: "inherit" });
fs.writeFileSync(path.join(migrations, "migration_lock.toml"), '# Please do not edit this file manually\nprovider = "postgresql"\n');

const hasInit = fs.existsSync(path.join(migrations, "0001_init"));
if (!hasInit) {
  const sql = run(["migrate", "diff", "--from-empty", "--to-schema-datamodel", schemaFile, "--script"], { encoding: "utf8" });
  fs.mkdirSync(path.join(migrations, "0001_init"));
  fs.writeFileSync(path.join(migrations, "0001_init", "migration.sql"), sql);
  console.log(`Wrote prisma/postgres (schema + 0001_init, ${sql.split("\n").length} lines of SQL)`);
} else if (previous === null || previous === pg) {
  console.log("prisma/postgres is already up to date: no new migration");
} else {
  const old = path.join(os.tmpdir(), `intelliq-previous-pg-${process.pid}.prisma`);
  fs.writeFileSync(old, previous);
  let sql;
  try {
    sql = run(["migrate", "diff", "--from-schema-datamodel", old, "--to-schema-datamodel", schemaFile, "--script"], { encoding: "utf8" });
  } finally {
    fs.rmSync(old, { force: true });
  }
  if (/^\s*(--[^\n]*\n\s*)*$/.test(sql) || /empty migration/i.test(sql)) {
    console.log("Schema text changed but the database structure did not: no new migration");
  } else {
    const stamp = new Date().toISOString().replace(/\D/g, "").slice(0, 14);
    const dir = path.join(migrations, `${stamp}_update`);
    fs.mkdirSync(dir);
    fs.writeFileSync(path.join(dir, "migration.sql"), sql);
    console.log(`Added migration ${path.basename(dir)} (${sql.split("\n").length} lines of SQL); existing migrations were not touched`);
  }
}
